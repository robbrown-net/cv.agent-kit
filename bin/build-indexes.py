#!/usr/bin/env python3
"""Regenerate the retrieval layer over the achievement bank.

Reads   <root>/profile/achievements.jsonl
        <root>/profile/vocab.json        (optional)
        <root>/profile/contested.json    (optional)
        <root>/config/user.json          (optional, key: never_claim)
Writes  <root>/profile/themes.md
        <root>/profile/figures.md

<root> is the parent of bin/ (resolved from this script's location), or --root.

Modes:
  (default)    write both files
  --check      exit 1 if either file on disk differs from generated content
  --selftest   build a fictional fixture and assert mapping, extraction, check mode

If achievements.jsonl is missing or empty, both files are written as stubs
saying the bank is empty and onboarding should be run. Standard library only.

---------------------------------------------------------------------------
OPTIONAL USER DATA FILES (schemas). Nothing personal lives in this script.
Copy profile/vocab.example.json and profile/contested.example.json to
profile/vocab.json and profile/contested.json and edit.
---------------------------------------------------------------------------

profile/vocab.json  (JSON object, every key optional)
  {
    "merge_map":      {"<raw tag>": "<controlled tag>", ...},
    "definitions":    {"<controlled tag>": "one-sentence definition", ...},
    "employer_short": {"<full employer name>": "<short name>", ...},
    "figure_exclude": ["<regex>", ...]
  }
  merge_map      folds the free-form tags in achievements.jsonl "themes" into a
                 smaller controlled vocabulary. With no merge_map every raw tag
                 is its own controlled tag. If a merge_map is present, raw tags
                 missing from it pass through unchanged and are listed under
                 "Unmapped tags" in themes.md so you can add them.
                 The controlled tag "confirmed-constraints" is reserved: records
                 carrying it are session notes about what may be written, and
                 only their structured metric is mined for figures.
  definitions    shown under each controlled tag in themes.md.
  employer_short short labels used in the theme gists.
  figure_exclude extra regexes (case-insensitive) for numeric-looking text that
                 is a name or version, not a claimable figure (e.g. "\\bMK\\d\\b").

profile/contested.json  (JSON list, or an object with the keys below)
  [ {"subject": "...", "a": "version A", "b": "version B",
     "wins": "which may be written, or UNRESOLVED / do not use",
     "why": "reason"} , ... ]
  or
  {"contested": [ ...same list... ], "unavailable": ["Numbers that must not be used", ...]}
  Contested items are printed at the top of figures.md. "unavailable" lines are
  printed under "Numbers that are explicitly NOT available", together with
  config/user.json never_claim.
"""

