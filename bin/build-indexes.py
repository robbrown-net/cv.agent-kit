def build(root):
    root = Path(root)
    profile = root / "profile"
    records = load_records(profile / "achievements.jsonl")
    config = load_json(root / "config" / "user.json")
    never = config.get("never_claim") if isinstance(config, dict) else []
    ctx = Context(load_json(profile / "vocab.json"), load_json(profile / "contested.json"),
                  never if isinstance(never, list) else [])
    return {
        profile / "themes.md": render_themes(records, ctx),
        profile / "figures.md": render_figures(records, ctx),
    }, records, ctx


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, help="repo root (default: parent of bin/)")
    parser.add_argument("--check", action="store_true", help="exit 1 if files on disk are stale")
    parser.add_argument("--selftest", action="store_true", help="run the built-in fixture tests")
    args = parser.parse_args(argv)

    if args.selftest:
        return selftest()

    root = (args.root or Path(__file__).resolve().parent.parent).resolve()
    try:
        outputs, records, ctx = build(root)
    except DataError as exc:
        sys.stderr.write("ERROR: %s\n" % exc)
        return 2

    if args.check:
        stale = []
        for path, content in outputs.items():
            if not path.exists():
                stale.append("%s is missing" % path)
            elif path.read_text(encoding="utf-8") != content:
                stale.append("%s is out of date" % path)
        if stale:
            for line in stale:
                sys.stderr.write("STALE: %s\n" % line)
            sys.stderr.write("Run bin/build-indexes.py to regenerate.\n")
            return 1
        print("OK: themes.md and figures.md match achievements.jsonl (%d records)." % len(records))
        return 0

    unmapped = set()
    for record in records:
        controlled_themes(record, ctx, unmapped)
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print("wrote %s (%d lines)" % (path, content.count("\n")))
    if not records:
        print("note: bank is empty, wrote stub index files. Run onboarding.")
    if unmapped:
        sys.stderr.write("WARNING: tags missing from vocab.json merge_map: %s\n" % ", ".join(sorted(unmapped)))
    return 0


