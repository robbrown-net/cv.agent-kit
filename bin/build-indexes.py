CONF_SCORE = {"high": 3, "medium": 1, "low": 0, "conflicted": -2}


class DataError(Exception):
    pass


def load_records(path):
    """Records from a JSONL file. Missing or empty file gives []."""
    path = Path(path)
    if not path.is_file():
        return []
    records = []
    with open(path, "r", encoding="utf-8") as handle:
        for number, line in enumerate(handle, start=1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError as exc:
                raise DataError("%s line %d is not valid JSON: %s" % (path, number, exc))
            if not isinstance(record, dict):
                raise DataError("%s line %d is not a JSON object" % (path, number))
            records.append(record)
    return records


def load_json(path):
    path = Path(path)
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise DataError("%s is not valid JSON: %s" % (path, exc))


class Context:
    """User-supplied data that shapes the output. All of it optional."""

    def __init__(self, vocab=None, contested=None, never_claim=None):
        vocab = vocab if isinstance(vocab, dict) else {}
        self.merge_map = {k: v for k, v in (vocab.get("merge_map") or {}).items()
                          if not k.startswith("_")}
        self.definitions = {k: v for k, v in (vocab.get("definitions") or {}).items()
                            if not k.startswith("_")}
        self.employer_short = {k: v for k, v in (vocab.get("employer_short") or {}).items()
                               if not k.startswith("_")}
        self.exclude = []
        for pattern in vocab.get("figure_exclude") or []:
            try:
                self.exclude.append(re.compile(pattern, re.I))
            except re.error as exc:
                raise DataError("vocab.json figure_exclude %r is not a valid regex: %s" % (pattern, exc))
        if isinstance(contested, dict):
            items = contested.get("contested") or []
            unavailable = contested.get("unavailable") or []
        elif isinstance(contested, list):
            items, unavailable = contested, []
        else:
            items, unavailable = [], []
        self.contested = [i for i in items if isinstance(i, dict) and i.get("subject")]
        self.unavailable = [str(u) for u in unavailable] + [str(n) for n in (never_claim or [])]

    def controlled_tags(self):
        return set(self.merge_map.values()) | set(self.definitions)

    def short(self, name):
        return self.employer_short.get(name, name)


def scale_score(record):
    metric = record.get("metric")
    if not metric:
        return 0
    value = metric.get("value")
    if not isinstance(value, (int, float)):
        return 0
    value = abs(float(value))
    if metric.get("type") == "percent":
        return 2 if value >= 50 else 1
    for threshold, points in ((1_000_000, 4), (10_000, 3), (100, 2), (10, 1)):
        if value >= threshold:
            return points
    return 0


def strength(record):
    return (
        (3 if record.get("metric") else 0)
        + CONF_SCORE.get(record.get("confidence"), 0)
        + scale_score(record)
    )


def _rid(record):
    return str(record.get("id", "(no id)"))


def _employer(record):
    return str(record.get("employer", "(unknown employer)"))


def controlled_themes(record, ctx, unmapped):
    """Controlled tags for a record. With no merge_map, raw tags stand as they are."""
    out = []
    for raw in record.get("themes") or []:
        if ctx.merge_map:
            mapped = ctx.merge_map.get(raw)
            if mapped is None:
                unmapped.add(raw)
                mapped = raw
        else:
            mapped = raw
        if mapped not in out:
            out.append(mapped)
    return out


def _registers(record):
    reg = record.get("register")
    if isinstance(reg, str):
        return [reg]
    return list(reg or []) or ["unset"]


