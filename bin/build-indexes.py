GIST_CUT = 66


def gist(claim):
    """A short orientation phrase for a claim. Never quotable, never a source of figures."""
    text = _clean(claim)
    for sep in (" - ", "; ", ": "):
        idx = text.find(sep)
        if 0 < idx < GIST_CUT + 25:
            text = text[:idx]
            break
    if len(text) > GIST_CUT:
        return text[:GIST_CUT].rsplit(" ", 1)[0].rstrip(" ,.;:") + "..."
    return text.rstrip(" ,.")


def _wrap_ids(ids, width=8):
    return "\n".join(", ".join(ids[i:i + width]) for i in range(0, len(ids), width))


def _period_span(periods):
    years = []
    for p in periods:
        years.extend(re.findall(r"\d{4}", str(p)))
    if not years:
        return "n/a"
    lo, hi = min(years), max(years)
    if any(str(p).rstrip().endswith("-") for p in periods):
        return "%s-" % lo
    return lo if lo == hi else "%s-%s" % (lo, hi)


def _esc(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def render_themes(records, ctx):
    if not records:
        return EMPTY_STUB.format(title="Theme, employer and register index")
    unmapped = set()
    by_theme = {}
    raw_counts = {}
    for record in records:
        for raw in record.get("themes") or []:
            raw_counts[raw] = raw_counts.get(raw, 0) + 1
        for tag in controlled_themes(record, ctx, unmapped):
            by_theme.setdefault(tag, []).append(record)

    lines = ["# Theme, employer and register index", "",
             "Generated by `build-indexes.py`. Do not edit by hand.", "",
             THEMES_PREAMBLE.rstrip(), "",
             "- Records indexed: %d" % len(records),
             "- Raw theme tags in the bank: %d" % len(raw_counts),
             "- Controlled tags: %d" % len(by_theme), "",
             "Ordering inside every list is strongest first: has a structured metric, then",
             "confidence, then scale of the number.", ""]
    seen = {}
    for record in records:
        seen[_rid(record)] = seen.get(_rid(record), 0) + 1
    dupes = sorted(i for i, n in seen.items() if n > 1)
    if dupes:
        lines += ["**Duplicate ids in the bank, fix at source:** %s. An id that resolves to two"
                  % ", ".join("`%s`" % d for d in dupes),
                  "different records cannot be cited safely. Quote the claim text, not the id,",
                  "until this is resolved.", ""]

    if ctx.merge_map:
        lines += ["## Controlled vocabulary, and the merge that produced it", "",
                  "One controlled tag per line, then the raw tags folded into it.", "",
                  "| Controlled tag | Raw tags merged in |", "| --- | --- |"]
        for tag in sorted(ctx.controlled_tags()):
            raws = sorted(r for r, v in ctx.merge_map.items() if v == tag)
            marked = ["**%s**" % r if r == tag else r for r in raws]
            lines.append("| `%s` | %s |" % (tag, ", ".join(marked)))
        lines += ["", "Bold means the raw tag kept its own name. Every other raw tag was folded in."]
        if unmapped:
            lines += ["", "**Unmapped tags, add them to `profile/vocab.json` merge_map:** "
                      + ", ".join("`%s`" % t for t in sorted(unmapped))]
        lines.append("")

    lines += ["## By theme", "",
              "Each tag gives its definition (if one is set), then the three strongest records in",
              "one line each, then every id in the tag. Pull the record before writing from it:",
              "the gists below are orientation, not quotable text, and any number in a gist must",
              "still be taken from `figures.md`.", ""]
    for tag in sorted(by_theme, key=lambda t: (-len(by_theme[t]), t)):
        group = sorted(by_theme[tag], key=lambda r: (-strength(r), _rid(r)))
        lines += ["### `%s` (%d)" % (tag, len(group)), ""]
        if tag in ctx.definitions:
            lines += [ctx.definitions[tag], ""]
        for record in group[:3]:
            lines.append("- `%s` %s: %s" % (_rid(record), ctx.short(_employer(record)), gist(str(record.get("claim", "")))))
        lines += ["", _wrap_ids([_rid(r) for r in group]), ""]

    lines += ["## By employer", "", "Employers ordered by record count. Ids strongest first.", ""]
    by_employer = {}
    for record in records:
        by_employer.setdefault(_employer(record), []).append(record)
    lines += ["| Employer | Period | N | Ids, strongest first |", "| --- | --- | --- | --- |"]
    for employer in sorted(by_employer, key=lambda e: (-len(by_employer[e]), e)):
        group = sorted(by_employer[employer], key=lambda r: (-strength(r), _rid(r)))
        period = _period_span([r.get("period") for r in group if r.get("period")])
        lines.append("| %s | %s | %d | %s |" % (_esc(employer), period, len(group), ", ".join(_rid(r) for r in group)))
    lines.append("")

    lines += ["## By register", "",
              "`exec` reads at board and leadership level, `delivery` at team and delivery level,",
              "`practitioner` at hands-on level. Records may carry several. Strongest first.", ""]
    by_register = {}
    for record in records:
        for reg in _registers(record):
            by_register.setdefault(reg, []).append(record)
    for reg in sorted(by_register):
        group = sorted(by_register[reg], key=lambda r: (-strength(r), _rid(r)))
        lines += ["### `%s` (%d)" % (reg, len(group)), "",
                  "Strongest 30: " + ", ".join(_rid(r) for r in group[:30]), ""]

    lines += ["## Low confidence, use with care", "",
              "Do not build a headline claim on these, and never take a figure from one",
              "without checking `figures.md` first.", ""]
    weak = [r for r in records if r.get("confidence") in ("low", "conflicted")]
    for conf in ("conflicted", "low"):
        group = [r for r in weak if r.get("confidence") == conf]
        if group:
            lines.append("- **%s**: %s" % (conf, ", ".join(
                "`%s` (%s)" % (_rid(r), ctx.short(_employer(r))) for r in sorted(group, key=_rid))))
    if not weak:
        lines.append("None.")
    lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_figures(records, ctx):
    if not records:
        return EMPTY_STUB.format(title="Figures the bank supports")
    rows, flagged = [], []
    for record in records:
        employer, rid = _employer(record), _rid(record)
        conf = record.get("confidence", "unknown")
        claim = str(record.get("claim", ""))
        metric = record.get("metric")
        # Records tagged confirmed-constraints are session notes about what may or
        # may not be written. Mining their prose would surface the very numbers
        # they exist to forbid, so only their structured metric is taken.
        meta = ("confirmed-constraints" in controlled_themes(record, ctx, set())
                or META_CLAIM.search(claim) is not None)
        prose = [] if meta else extract_prose_figures(claim, ctx.exclude)

        if isinstance(metric, dict) and metric:
            figure, unit = format_metric(metric)
            note = ""
            if not metric_corroborated(metric, claim):
                note = "verify"
                flagged.append((rid, employer, figure, unit, claim))
            lead = _lead_number(figure)
            match = None
            for text, _measures in prose:
                if lead is not None and _lead_number(text) == lead:
                    match = text
                    break
            if match is not None:
                prose = [p for p in prose if _lead_number(p[0]) != lead]
                figure = _fold(figure, match, metric.get("type"))
            rows.append({"employer": employer, "figure": figure,
                         "measures": unit or _clause_for(claim, 0, 0),
                         "id": rid, "conf": conf, "src": "metric", "note": note})
        for text, measures in prose:
            rows.append({"employer": employer, "figure": text, "measures": measures,
                         "id": rid, "conf": conf, "src": "claim", "note": ""})

    lines = ["# Every figure the bank supports", "",
             "Generated by `build-indexes.py`. Do not edit by hand.", "",
             FIGURES_PREAMBLE.rstrip(), "",
             "Figures extracted: **%d** across **%d** records. Source column: `metric` means the"
             % (len(rows), len(set(r["id"] for r in rows))),
             "record's structured metric field, `claim` means the number sits in the claim prose.", ""]

    if ctx.contested:
        lines += ["## CONTESTED FIGURES, read before the table", "",
                  "Sources disagree on every item below. The winner column is what may be written today.",
                  "Where the winner is UNRESOLVED or 'do not use', no number goes in the document.", ""]
        for item in ctx.contested:
            lines += ["### %s" % item["subject"], "",
                      "- Version A: %s" % item.get("a", ""),
                      "- Version B: %s" % item.get("b", ""),
                      "- **Wins: %s**" % item.get("wins", "UNRESOLVED"),
                      "- Why: %s" % item.get("why", ""), ""]

    if flagged:
        lines += ["## AMBIGUOUS FIGURES, structured metric not corroborated by its own claim", "",
                  "In each of these the `metric` field carries a value that does not appear in the",
                  "record's claim text. That is either a rounding, a derived figure or a data entry",
                  "error. Read the record before using the number, and prefer the prose.", "",
                  "| Id | Employer | Metric field says | Claim prose says |", "| --- | --- | --- | --- |"]
        for rid, employer, figure, unit, claim in sorted(flagged):
            snippet = claim if len(claim) <= 160 else claim[:157].rsplit(" ", 1)[0] + "..."
            lines.append("| `%s` | %s | %s (%s) | %s |" % (rid, _esc(employer), figure, _esc(unit), _esc(snippet)))
        lines.append("")

    lines += ["## The table", "",
              "| Figure, write it exactly like this | What it measures | Employer | Id | Confidence | Source |",
              "| --- | --- | --- | --- | --- | --- |"]
    for row in sorted(rows, key=lambda r: (r["employer"].lower(), r["id"], r["figure"].lower())):
        figure = row["figure"] + (" (verify)" if row["note"] else "")
        lines.append("| %s | %s | %s | `%s` | %s | %s |" % (
            _esc(figure), _esc(row["measures"]), _esc(row["employer"]),
            row["id"], row["conf"], row["src"]))
    lines.append("")

    if ctx.unavailable:
        lines += ["## Numbers and claims that are explicitly NOT available", ""]
        lines += ["- %s" % item for item in ctx.unavailable]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


