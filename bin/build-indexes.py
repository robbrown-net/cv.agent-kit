NUM = r"(?:\d[\d,]*(?:\.\d+)?)"
QUAL = r"(?:over|under|around|about|approximately|more than|less than|nearly|at least|up to|roughly|some|just|~)\s+"

FIGURE_PATTERNS = [
    # currency, including ranges and plus signs
    re.compile(r"(?:" + QUAL + r")?(?:GBP|EUR|USD|\$|£|€)\s?" + NUM + r"(?:\s?(?:to|-)\s?" + NUM + r")?\s?(?:[kKmMbB]\b|million|billion|thousand)?\+?(?:\s?(?:a|per)\s+year)?", re.I),
    # explicit percentages
    re.compile(r"(?:" + QUAL + r")?" + NUM + r"(?:\s?to\s?" + NUM + r")?\s?(?:%|per cent|percent)", re.I),
    # nines notation
    re.compile(r"\b(?:five|six|four|three)-nines\b", re.I),
    # multipliers
    re.compile(r"\b" + NUM + r"\s?x\b(?:\s+target)?", re.I),
    # durations
    re.compile(r"(?:" + QUAL + r")?(?:" + NUM + r"|one|two|three|four|five|six|seven|eight|nine|ten|eleven|twelve)\s+(?:minute|hour|day|week|fortnight|month|quarter|year)s?", re.I),
    # dates
    re.compile(r"\b\d{1,2}\s+(?:January|February|March|April|May|June|July|August|September|October|November|December)\s+\d{4}\b"),
    # counted things: number (plus optional +) followed by up to three words
    re.compile(r"(?<![$£€\w.])(?:" + QUAL + r")?" + NUM + r"\+?(?:[kKmM]\b|\s?(?:million|billion|thousand))?\s+(?:[a-z][\w'-]*\s+){0,2}[a-z][\w'-]*", re.I),
]

TAIL_STOP = {
    "a", "an", "the", "and", "or", "but", "of", "to", "in", "on", "for", "with",
    "by", "as", "at", "from", "per", "into", "across", "over", "under", "after",
    "before", "through", "using", "that", "which", "who", "so", "then", "still",
    "was", "were", "is", "are", "had", "has", "have", "he", "his", "she", "her",
    "it", "its", "consistently", "frequently", "directly", "himself", "herself",
    "each", "both", "no",
}

# Numeric-looking text that is a label, not a claimable figure. Extend per user
# through "figure_exclude" in profile/vocab.json.
EXCLUDE = [re.compile(p, re.I) for p in (
    r"\bPhase\s?\d", r"\blevel\s?\d", r"\bYear\s?\d\b", r"\bTier\s?\d", r"\bStage\s?\d",
    r"\bQ[1-4]\b", r"\bP[0-4]/P[0-4]\b", r"\b\d{4}/\d{2}\b", r"\b\d{4}-\d{2}-\d{2}\b",
)]

BARE_YEAR = re.compile(r"^(?:19|20)\d{2}\b")


def _clean(text):
    return re.sub(r"\s+", " ", text).strip(" ,.;:-")


def _clause_for(claim, start, end):
    """The clause of the claim containing the span, for the 'what it measures' column."""
    left = max(claim.rfind(";", 0, start), claim.rfind(" - ", 0, start))
    lcomma = claim.rfind(",", 0, start)
    if lcomma > left and start - lcomma < 90:
        left = lcomma
    left = 0 if left < 0 else left + 1
    right = len(claim)
    for sep in (";", " - "):
        idx = claim.find(sep, end)
        if idx != -1:
            right = min(right, idx)
    idx = claim.find(",", end)
    if idx != -1 and idx - end < 90:
        right = min(right, idx)
    out = _clean(claim[left:right])
    if len(out) > 150:
        out = out[:147].rsplit(" ", 1)[0] + "..."
    return out


def extract_prose_figures(claim, extra_exclude=()):
    """Return a list of (figure_text, measures_text) found in claim prose."""
    excludes = list(EXCLUDE) + list(extra_exclude)
    spans = []
    for pat in FIGURE_PATTERNS:
        for m in pat.finditer(claim):
            text = _clean(m.group(0))
            if not text or not re.search(r"\d|nines", text, re.I):
                continue
            window = claim[max(0, m.start() - 12):m.end() + 12]
            if any(x.search(window) for x in excludes):
                continue
            words = text.split()
            trimmed = []
            for i, word in enumerate(words):
                if i > 0 and word.strip(",.;:").lower() in TAIL_STOP:
                    break
                trimmed.append(word)
            text = _clean(" ".join(trimmed))
            if not text or not re.search(r"\d|nines", text, re.I):
                continue
            if BARE_YEAR.match(text) and not re.match(r"^(?:19|20)\d{2}\s*(?:%|per cent|percent)", text, re.I):
                continue
            spans.append((m.start(), m.end(), text))
    spans.sort(key=lambda s: (s[0], -(s[1] - s[0])))
    kept = []
    for s in spans:
        if any(s[0] >= k[0] and s[1] <= k[1] for k in kept):
            continue
        kept.append(s)
    out = []
    seen = set()
    for start, end, text in kept:
        key = text.lower()
        if key in seen:
            continue
        seen.add(key)
        out.append((text, _clause_for(claim, start, end)))
    return out


def format_metric(metric):
    """Render a structured metric field as the figure exactly as it should be written."""
    mtype = metric.get("type")
    value = metric.get("value")
    unit = (metric.get("unit") or "").strip()
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    if mtype == "money":
        cur = "GBP"
        for token in ("GBP", "USD", "EUR", "$", "£", "€"):
            if token in unit:
                cur = "USD" if token == "$" else ("GBP" if token == "£" else ("EUR" if token == "€" else token))
                break
        return "%s %s" % (cur, _short_money(value)), unit
    if mtype == "percent":
        return "%s%%" % _plain(value), unit
    if mtype in ("time", "duration"):
        head = unit.split()[0] if unit else ""
        rest = unit[len(head):].strip() or unit
        return _clean("%s %s" % (_plain(value), head)), rest
    if unit.lower().startswith("x "):
        return "%sx" % _plain(value), unit[2:].strip()
    return _plain(value), unit


def _plain(value):
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    return "{:,}".format(value) if isinstance(value, int) else str(value)


def _short_money(value):
    if not isinstance(value, (int, float)):
        return str(value)
    value = int(value)
    if value >= 1_000_000 and value % 100_000 == 0:
        return "%gm" % (value / 1_000_000)
    if value >= 1000 and value % 1000 == 0:
        return "%dk" % (value // 1000)
    return "{:,}".format(value)


# Claims that are session notes about what may be written, not achievements.
META_CLAIM = re.compile(r"(?:User|Candidate) confirmed on|Do not (?:ask|write|use)|CONFLICT:", re.I)

QUAL_PREFIX = re.compile(r"^(over|under|around|about|approximately|more than|less than|nearly|at least|up to|roughly|~)\s+", re.I)
COMPACT = re.compile(r"(\d[\d,]*(?:\.\d+)?\s?(?:[kKmMbB]|x))\b")


def _fold(metric_figure, prose_text, mtype):
    """Combine a metric's clean figure with the way the prose actually writes it."""
    out = metric_figure
    if mtype != "money":
        compact = COMPACT.search(prose_text)
        if compact:
            out = compact.group(1).replace(" ", "")
    if re.search(r"\d[\w,\.]*\+", prose_text) and not out.endswith("+"):
        out += "+"
    qual = QUAL_PREFIX.match(prose_text)
    if qual and not out.startswith("+"):
        out = "%s %s" % (qual.group(1).lower(), out)
    return out


def _lead_number(text):
    match = re.search(r"\d[\d,]*(?:\.\d+)?", text)
    if not match:
        return None
    value = float(match.group(0).replace(",", ""))
    suffix = text[match.end():match.end() + 8].lower().lstrip()
    if suffix.startswith("m") or suffix.startswith("million"):
        value *= 1_000_000
    elif suffix.startswith("k") or suffix.startswith("thousand"):
        value *= 1000
    return value


def metric_corroborated(metric, claim):
    """True if the metric's value can be found in the claim prose in some readable form."""
    value = metric.get("value")
    if not isinstance(value, (int, float)):
        return True
    value = int(value) if float(value).is_integer() else value
    lowered = claim.lower().replace(",", "")
    forms = {str(value), "{:,}".format(value).replace(",", "")}
    if isinstance(value, int):
        if value >= 1_000_000 and value % 100_000 == 0:
            forms.add("%gm" % (value / 1_000_000))
            forms.add("%g million" % (value / 1_000_000))
        if value >= 1000 and value % 1000 == 0:
            forms.add("%dk" % (value // 1000))
            forms.add("{:,}".format(value))
        words = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six",
                 7: "seven", 8: "eight", 9: "nine", 10: "ten", 11: "eleven", 12: "twelve"}
        if value in words:
            forms.add(words[value])
        ordinals = {1: "first", 2: "second", 3: "third", 4: "fourth", 5: "fifth", 6: "sixth"}
        if value in ordinals:
            forms.add(ordinals[value])
    return any(f.lower() in lowered for f in forms)


